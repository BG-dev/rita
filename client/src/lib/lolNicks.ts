/** Случайный ник, не совпадающий с текущим. */
export function randomLolNick(exclude?: string): string {
  if (LOL_NICKS.length < 2) return LOL_NICKS[0] ?? "Гость";
  let pick = LOL_NICKS[Math.floor(Math.random() * LOL_NICKS.length)];
  for (let i = 0; i < 8 && pick === exclude; i++) {
    pick = LOL_NICKS[Math.floor(Math.random() * LOL_NICKS.length)];
  }
  return pick;
}
